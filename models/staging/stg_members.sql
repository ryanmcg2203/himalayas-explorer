select
    id,
    expeditionId as expedition_id,
    sourceExpid as source_expid,
    memberId as member_id,
    cast(year as integer) as year,
    peakId as peak_id,
    firstName as first_name,
    lastName as last_name,
    trim(concat(firstName, ' ', lastName)) as full_name,
    sex,
    cast(age as integer) as age,
    nullif(yob, '') as year_of_birth,
    citizen as citizenship,
    status,
    occupation,
    cast(leader as boolean) as is_leader,
    cast(support as boolean) as is_support,
    cast(hired as boolean) as is_hired,
    cast(sherpa as boolean) as is_sherpa,
    cast(tibetan as boolean) as is_tibetan,
    cast(success as boolean) as summit_success,
    cast(claimed as boolean) as summit_claimed,
    cast(disputed as boolean) as summit_disputed,
    cast(highPoint as boolean) as reached_high_point,
    cast(oxygen as boolean) as oxygen_used,
    cast(death as boolean) as died,
    deathDate as death_date,
    cast(deathType as integer) as death_type,
    cast(deathHeight as integer) as death_height_m,
    cast(deathClass as integer) as death_class,
    cast(ams as boolean) as had_ams,
    cast(weather as boolean) as weather_related,
    cast(injury as boolean) as injured
from read_json_auto('data/bronze/members.json.gz')
